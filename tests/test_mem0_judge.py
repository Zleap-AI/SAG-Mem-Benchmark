@pytest.mark.asyncio
@pytest.mark.parametrize("abstention", [True, False])
@pytest.mark.parametrize("answer,label,correct", [
    ("I cannot determine that from these conversations.", "CORRECT", True),
    ("No information available, but I guess blue.", "WRONG", False),
])
async def test_category_five_uses_llm_not_keyword_score(monkeypatch, abstention, answer, label, correct):
    create = mock_client(monkeypatch, json.dumps({"label": label}))
    record = {"hypothesis": answer}
    await b.score_record(record, b.Target("distractor must not be a reference", "5", abstention),
                         b.Query("color?"), LoCoMoProtocol(), ReaderGrader(judge_model="configured-qwen"),
                         {"question_date_text": True, "model_timeout": 10}, regrade=True)
    assert record["status"] == "succeeded" and record["grade"] is correct
    assert "bleu1" not in record["metrics"]
    if abstention:
        assert record["locomo_rule_score"] == float(not correct)  # LLM result may differ from keywords.
    assert create.call_args.kwargs == {
        "model": "configured-qwen", "temperature": 0,
        "response_format": {"type": "json_object"},
        "messages": [{"role": "user", "content": LOCOMO_ABSTENTION_PROMPT.format(
            question="color?", generated_answer=answer)}],
    }


@pytest.mark.parametrize("protocol", [None, "locomo", "locomo_mem0"])
def test_default_preflight_includes_adversarial_and_records_both_judges(tmp_path, protocol):
    options = source_options(tmp_path, protocol)
    examples, _, manifest = b.prepare_run(options)
    assert [e.target.category for e in examples] == ["1", "2", "3", "4", "5"]
    assert manifest["judge_reporting"]["categories"] == ["1", "2", "3", "4", "5"]
    assert manifest["judge_reporting"]["mem0_categories"] == ["1", "2", "3", "4"]
    assert manifest["judge_reporting"]["abstention_prompt_source"] == "local"
    assert manifest["identity"]["judge_reporting"] == manifest["judge_reporting"]
    assert manifest["run_id"] == b.fingerprint(manifest["identity"])
    assert LoCoMoProtocol.accepts_target(b.Target("", "5", True))
    with pytest.raises(ValueError, match="Unsupported LoCoMo category"):
        LoCoMoProtocol.accepts_target(b.Target("a", "temporal-reasoning"))


@pytest.mark.asyncio
async def test_regrade_five_categories_preserves_answers_source_and_resume(tmp_path, monkeypatch):
    opts = source_options(tmp_path)
    _, dependencies, _ = b.prepare_run(opts)
    # Reconstruct an old five-category run to verify protocol migration uses a new output identity.
    examples = b.resolve("dataset", "locomo")().scan(opts)
    original_manifest = b.run_manifest(opts, examples, dependencies)
    legacy_metadata = json.loads((Path(__file__).parent / "fixtures" / "locomo_judge_v1.json").read_text())[
        "metadata"]
    original_manifest["judge_reporting"] = legacy_metadata
    original_manifest["identity"]["judge_reporting"] = legacy_metadata
    original_manifest["run_id"] = b.fingerprint(original_manifest["identity"])
    source = Path(opts["output"])
    store = b.ResultStore(source, original_manifest)
    for e in examples:
        store.append({"question_id": e.id, "run_id": original_manifest["run_id"], "protocol": "locomo",
                      "hypothesis": "blue", "query": asdict(e.query), "target": asdict(e.target),
                      "question_type": e.target.category, "grade": False, "reader_prompt_tokens": 999,
                      "status": "succeeded"})
    store.close()
    source_bytes = source.read_bytes()
    manifest_bytes = source.with_suffix(".jsonl.manifest.json").read_bytes()
    _, _, current_manifest = b.prepare_run(opts)
    with pytest.raises(ValueError, match="identity mismatch"):
        b.ResultStore(source, current_manifest, resume=True)
    create = mock_client(monkeypatch, '{"label":"CORRECT"}')
    respond = AsyncMock(side_effect=AssertionError("Reader must not run"))
    monkeypatch.setattr(ReaderGrader, "respond", respond)
    monkeypatch.setattr(b, "BackendProcess", lambda *a: pytest.fail("Backend must not run"))
    out = tmp_path / "mem0.jsonl"
    options = parse_args(["--regrade-from", str(source), "--output", str(out)])
    summary = await b.regrade(options)
    assert create.await_count == 5 and respond.await_count == 0
    assert summary["total"] == summary["valid_grades"] == 5 and summary["accuracy"] == 1
    report = summary["locomo_evaluation"]
    assert report["evaluation_complete"] and report["judge_macro_accuracy"] == 1
    assert report["by_category"]["adversarial"]["graded"] == 1
    assert report["mem0"]["graded"] == 4 and report["mem0"]["judge_accuracy"] == 1
    assert report["judge_protocol_version"] == "locomo-mem0-abstention-v1"
    assert summary["source_comparison"]["gained"] == 5
    manifest = json.loads(out.with_suffix(".jsonl.manifest.json").read_text())
    assert manifest["source_records"] == 5 and manifest["excluded_records"] == 0
    assert manifest["selected_records"] == 5 and len(manifest["question_order"]) == 5
    assert manifest["run_id"] == b.fingerprint(manifest["identity"])
    rows = b.read_records(out)
    assert all(r["hypothesis"] == "blue" and r["reader_prompt_tokens"] == 999 for r in rows)
    assert all(r["protocol"] == "locomo" and r["source_grade"] is False for r in rows)
    await b.regrade({**options, "resume": True})
    assert create.await_count == 5
    assert source.read_bytes() == source_bytes
    assert source.with_suffix(".jsonl.manifest.json").read_bytes() == manifest_bytes
    with pytest.raises(ValueError, match="identity mismatch"):
        await b.regrade({**options, "judge_model": "different-judge", "explicit": ["judge_model"], "resume": True})
