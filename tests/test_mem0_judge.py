def source_options(tmp_path, protocol=None):
    data = tmp_path / "data.json"
    data.write_text(json.dumps([{"sample_id": "c", "conversation": {
        "session_1": [{"dia_id": "D1:1", "speaker": "A", "text": "blue"}],
        "session_1_date_time": "2023/01/01 (Sun) 10:00"}, "qa": [
        {"category": cat, "question": "color?", "answer": "blue", "evidence": ["D1:1"]}
        for cat in range(1, 6)]}]))
    return parse_args(["--dataset", "locomo", "--backend", "full_context",
                       *(["--protocol", protocol] if protocol else []),
                       "--data-path", str(data), "--output", str(tmp_path / "source.jsonl")])


def mock_client(monkeypatch, response):
    create = AsyncMock(return_value=SimpleNamespace(
        choices=[SimpleNamespace(message=SimpleNamespace(content=response))],
        usage=SimpleNamespace(prompt_tokens=100, completion_tokens=8),
    ))
    client = SimpleNamespace(chat=SimpleNamespace(completions=SimpleNamespace(create=create)))
    monkeypatch.setattr(ReaderGrader, "_judge_client", property(lambda _: client))
    return create


def test_verbatim_prompt_matches_pinned_upstream_sha256():
    # Independently extracted from upstream ACCURACY_PROMPT at ec1d7a4, not generated by this module.
    expected = "44fb3d8f7a1f37b2430772cf90518a32172e4056b7a0dec085402763fd179b9f"
    assert hashlib.sha256(ACCURACY_PROMPT.encode()).hexdigest() == expected
    hashes = LoCoMoProtocol.reporting_metadata()["user_prompt_sha256"]
    assert all(hashes[category] == expected for category in ("1", "2", "3", "4"))
    assert hashes["5"] == hashlib.sha256(LOCOMO_ABSTENTION_PROMPT.encode()).hexdigest()
    assert hashes["5"] != expected


@pytest.mark.asyncio
@pytest.mark.parametrize("category", ["1", "2", "3", "4"])
@pytest.mark.parametrize("label,correct", [("CORRECT", True), ("WRONG", False)])
async def test_mem0_request_has_one_user_message_json_and_unchanged_model(monkeypatch, category, label, correct):
    create = mock_client(monkeypatch, json.dumps({"label": label}))
    grader = ReaderGrader(judge_model="configured-qwen")
    protocol = LoCoMoProtocol()
    record = {"hypothesis": "blue"}
    await b.score_record(record, b.Target("blue", category), b.Query("color?"), protocol, grader,
                         {"question_date_text": True, "model_timeout": 10}, regrade=True)
    assert record["grade"] is correct and record["status"] == "succeeded"
    assert record["grader_prompt_tokens"] == 100
    assert create.call_args.kwargs == {
        "model": "configured-qwen", "temperature": 0,
        "response_format": {"type": "json_object"},
        "messages": [{"role": "user", "content": ACCURACY_PROMPT.format(
            question="color?", gold_answer="blue", generated_answer="blue")}],
    }


